export function translate(lang: Language, key: string, vars?: Record<string, string | number>): string {
  let text = translations[lang][key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return text;
}
